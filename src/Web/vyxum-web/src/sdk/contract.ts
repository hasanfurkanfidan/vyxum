/** The import map: bare specifier → shim URL. */
export function importMap(): { imports: Record<string, string> } {
  const imports: Record<string, string> = {};
  for (const shared of SHARED_MODULES) {
    for (const specifier of shared.specifiers) imports[specifier] = SHARED_PATH + shared.file;
  }
  return { imports };
}

const identifier = /^[A-Za-z_$][\w$]*$/;
const reserved = new Set(['default', 'module', 'exports', '__esModule']);

/** Source of a shim ES module that re-exports `names` of the shared module `key` from the shared global. */
export function shimSource(key: string, names: readonly string[]): string {
  const exported = [...new Set(names)].filter((n) => identifier.test(n) && !reserved.has(n)).sort();
  const lines = [
    '// Generated by the Vyxum web build: re-exports a module of the web application to separately built modules.',
    `const shared = globalThis[${JSON.stringify(SHARED_GLOBAL)}];`,
    `const m = shared && shared[${JSON.stringify(key)}];`,
    `if (!m) throw new Error(${JSON.stringify(`Vyxum shared module '${key}' is not available; the web application must load first.`)});`,
    'export default m.default ?? m;',
  ];
  if (exported.length > 0) {
    lines.push(`export const ${exported.map((n) => `${n} = m.${n}`).join(',\n  ')};`);
  }
  return lines.join('\n') + '\n';
}
