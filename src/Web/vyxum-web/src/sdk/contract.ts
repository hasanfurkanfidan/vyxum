// The contract between the web application and the screens of separately built modules.
// Plain data without imports: the Vite config reads it too (shim files and the import map).

/**
 * Version of the module SDK (`@vyxum/sdk` and the `register(host)` contract). Raise it when the SDK gains something;
 * never remove or change what an earlier version offered, so modules built for an older version keep working.
 */
export const SDK_VERSION = 1;

/** Oldest SDK version this application still serves. */
export const MIN_SDK_VERSION = 1;

/** Global the application fills before any module is imported; the shim files read it. */
export const SHARED_GLOBAL = '__vyxumShared';

/** URL folder of the shim files (emitted by the build, served by the dev server). */
export const SHARED_PATH = '/vyxum-shared/';

export interface SharedModule {
  /** Key in the shared global. */
  key: string;
  /** File name of the shim under SHARED_PATH. */
  file: string;
  /** Bare specifiers that modules import and the import map points at the shim. */
  specifiers: readonly string[];
  /** npm package to read the export names from at build time; the SDK lists its own names instead. */
  packageName?: string;
  /** Export names to write into the shim when there is no package to read them from. */
  names?: readonly string[];
}

/** What a module may import as a bare specifier. Everything else must be bundled into the module. */
